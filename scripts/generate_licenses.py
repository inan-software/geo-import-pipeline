"""Writes THIRD_PARTY_LICENSES.md from the installed packages and fails on forbidden licenses.

Usage: generate_licenses.py [--check] [--output PATH]
With --check the file is only compared, which makes the script usable in CI.
"""

from __future__ import annotations

import argparse
import re
import sys
from importlib.metadata import distributions
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FORBIDDEN = re.compile(r"\b(A?GPL|LGPL|GNU (Affero |Lesser )?General Public)", re.IGNORECASE)
SKIP = {"pip", "setuptools", "wheel", "geo-import-pipeline"}

HEADER = """# Third-party licenses

Generated by `scripts/generate_licenses.py`. Do not edit by hand.

## Python packages (runtime)

| Package | Version | License |
|---|---|---|
"""

FOOTER = """
`certifi` (MPL-2.0) is used unmodified. MPL-2.0 is a file-level license and does not
extend to the code of this project.

## Python packages (tests only, not part of the runtime image)

| Package | Version | License |
|---|---|---|
{dev}

## Separate programs, not linked into the code

| Program | Role | License |
|---|---|---|
| Info-ZIP `unzip` | Reads Deflate64 ZIP archives, started as an external process | Info-ZIP license (BSD-style) |
| PostgreSQL | Database service | PostgreSQL License |
| PostGIS | Database extension, separate service | GPL-2.0-or-later |

PostGIS runs as its own database service and is reached over the PostgreSQL protocol.
Its license therefore does not apply to the code of this project.
"""


def license_of(dist) -> str:
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License")]
    if classifiers:
        return ", ".join(classifiers)
    return (meta.get("License") or "UNKNOWN").strip().splitlines()[0][:60]


def pinned(path: Path) -> set[str]:
    names = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if "==" in line:
            names.add(normalize(line.split("==")[0]))
    return names


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def rows(names: set[str], installed: dict) -> str:
    lines = []
    for name in sorted(names):
        dist = installed.get(name)
        if dist is None:
            raise SystemExit(f"Pinned package is not installed: {name}")
        lines.append(f"| {dist.metadata['Name']} | {dist.version} | {license_of(dist)} |")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=ROOT / "THIRD_PARTY_LICENSES.md")
    args = parser.parse_args()

    installed = {normalize(d.metadata["Name"]): d for d in distributions()}
    runtime = pinned(ROOT / "requirements.txt")
    dev = pinned(ROOT / "requirements-dev.txt")

    offenders = [
        f"{dist.metadata['Name']} ({license_of(dist)})"
        for name, dist in installed.items()
        if name not in SKIP and (FORBIDDEN.search(license_of(dist)) or license_of(dist) == "UNKNOWN")
    ]
    if offenders:
        print("Forbidden or unknown licenses found: " + ", ".join(sorted(offenders)), file=sys.stderr)
        return 1

    text = HEADER + rows(runtime, installed) + "\n" + FOOTER.format(dev=rows(dev, installed))
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != text:
            print("THIRD_PARTY_LICENSES.md is out of date", file=sys.stderr)
            return 1
        print("License overview is up to date, no forbidden licenses")
        return 0
    args.output.write_text(text, encoding="utf-8")
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
